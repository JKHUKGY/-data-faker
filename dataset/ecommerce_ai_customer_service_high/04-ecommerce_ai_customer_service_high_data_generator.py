def gen_annotation_ground_truth(n: int = 500, ticket_df: pl.DataFrame = None) -> pl.DataFrame:
    """Generate human-annotated Ground Truth data

    n = number of evaluation sample tickets (~500), not the total ticket count (5000).

    Critical fixes:
    - Evaluation sample changed to "stratified random sampling": from tickets submitted
      before 2024-11-07, do stratified random sampling of n tickets by true_intent
      -> the sample covers all 7 generated intents, no longer degenerating to a single
      dispute_non_receipt. (Restricting to early submissions is to keep annotation/evaluation
      ordering valid: annotation after submission, before the first 2024-11-10 evaluation.)
    - True intent is taken directly from the ticket's true_intent column (no longer keyword-inferred).
    - annotation_date is after the ticket's submitted_at (satisfying temporal constraint).
    - Dual-annotation agreement rate ~95% (the two annotators directly aligned, rather than
      each independently 95% which would only yield ~90% joint agreement).
    """
    if ticket_df is None:
        raise ValueError("需要提供ticket数据")

    annotators = ["ANN001", "ANN002", "ANN003", "ANN004", "ANN005"]

    # Candidate pool: early-submitted tickets (ensures annotation is after submission, before first evaluation 2024-11-10)
    cutoff = datetime(2024, 11, 7)
    pool = ticket_df.filter(pl.col("submitted_at") <= cutoff).to_dicts()
    if len(pool) < n:  # Fallback: if not enough candidates, relax to the full set
        pool = ticket_df.to_dicts()

    # Stratified sample by true_intent, each intent gets a quota proportional to its share in the pool
    by_intent: dict[str, list] = {}
    for row in pool:
        by_intent.setdefault(row["true_intent"], []).append(row)

    sampled: list = []
    for intent, rows in by_intent.items():
        random.shuffle(rows)
        quota = max(1, round(n * len(rows) / len(pool)))
        sampled.extend(rows[:quota])
    random.shuffle(sampled)
    sampled = sampled[:n]

    records = []
    for row in sampled:
        ticket_id = row["ticket_id"]
        true_intent = row["true_intent"]
        submitted_at = row["submitted_at"]

        # Annotator 1's label: ~93% hits true intent, ~7% business-realistic misclassification
        label1 = true_intent if random.random() < 0.93 else _confusable_wrong(true_intent)
        # Annotator 2: 95% agrees with annotator 1 -> dual-annotator agreement ~95%
        label2 = label1 if random.random() < 0.95 else _confusable_wrong(label1)

        # Annotation date: completed 1~2 days after submission (after ticket, before 2024-11-10 first evaluation)
        annotation_date = submitted_at + timedelta(days=random.randint(1, 2))

        for annotator, labeled_intent in zip(random.sample(annotators, k=2), [label1, label2]):
            records.append({
                "annotation_id": len(records) + 1,
                "ticket_id": ticket_id,
                "annotator_id": annotator,
                "annotation_date": annotation_date,
                "true_primary_intent": labeled_intent,
                "true_secondary_intents": json.dumps([], ensure_ascii=False),
                "true_sentiment": random.choices(
                    ["neutral", "frustrated", "angry", "satisfied"],
                    weights=[0.50, 0.25, 0.20, 0.05])[0],
                "true_urgency": random.choices(
                    ["low", "medium", "high"], weights=[0.30, 0.40, 0.30])[0],
                # Confidence distribution (ER §7.3): 60% level-3 / 35% level-2 / 5% level-1
                "annotator_confidence": random.choices([3, 2, 1], weights=[0.60, 0.35, 0.05])[0],
                "annotation_notes": fake.text(max_nb_chars=50) if random.random() < 0.15 else None,
                "annotation_version": "v2",
            })

    return pl.DataFrame(records)


